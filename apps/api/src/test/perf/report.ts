import { closeDatabase } from '../../db/client.ts'
import { HOT_PATHS, type Measurement, measure } from './hot-paths.ts'
import { perfFixtures } from './harness.ts'
import { planSummary } from '../explain.ts'

/**
 * Writes `.artifacts/perf.md` — a table an AI (or a person) can read and diff between runs.
 *
 * The report is generated separately from the assertions on purpose. `bun run perf` answers "did
 * anything regress"; this answers "what does the database actually do", including the full plan
 * trees, which is what you need when the answer to the first question is yes.
 */

const OUTPUT = '.artifacts/perf.md'

function table(measurements: readonly Measurement[]): string {
  const header =
    '| Hot path | Queries (small / large) | Budget | Slowest statement | Dimension varied |\n' +
    '|---|---|---|---|---|'
  const rows = measurements.map((m) => {
    const counts = `${m.smallCount} / ${m.largeCount}`
    const verdict = m.smallCount === m.largeCount ? counts : `**${counts} — N+1**`
    return `| ${m.path.name} | ${verdict} | ${m.path.maxQueries} queries, ${m.path.budgetMs}ms | ${m.slowestMs.toFixed(1)}ms | ${m.path.dimension} |`
  })
  return [header, ...rows].join('\n')
}

function detail(m: Measurement): string {
  return [
    `### ${m.path.name}`,
    '',
    m.path.why,
    '',
    `- Queries: ${m.smallCount} (small) / ${m.largeCount} (large), varying ${m.path.dimension}`,
    `- Slowest statement: ${m.slowestMs.toFixed(1)}ms`,
    `- Must not sequentially scan: ${m.path.noSeqScan.join(', ') || '—'}`,
    `- Must use: ${m.path.indexes.join(', ') || '—'}`,
    '',
    '```',
    m.plans.map(planSummary).join('\n\n'),
    '```',
  ].join('\n')
}

async function main(): Promise<void> {
  const fixtures = await perfFixtures()
  const measurements: Measurement[] = []
  for (const path of HOT_PATHS) {
    // Sequential on purpose: concurrent measurements contend for the same connections and
    // statistics, which is exactly what the timings are meant to reflect the absence of.
    // oxlint-disable-next-line no-await-in-loop
    measurements.push(await measure(path, fixtures))
    console.log(`measured: ${path.name}`)
  }

  const document = [
    '# Performance report',
    '',
    `Generated by \`bun run perf:report\` against ${fixtures.setLogCount.toLocaleString('en')} set logs,`,
    '10,000 shared exercises and 1,000 seeded plans. Timings are from this machine and are',
    'indicative; the query counts and the plans are the parts that must not change.',
    '',
    table(measurements),
    '',
    '## Plans',
    '',
    measurements.map((m) => detail(m)).join('\n\n'),
    '',
  ].join('\n')

  await Bun.write(OUTPUT, document)
  console.log(`Wrote ${OUTPUT}`)
  await closeDatabase()
}

await main()
